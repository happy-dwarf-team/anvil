"""PROTOTYPE of the `anvil` command-line tool (throwaway).

    anvil gen   <symbols.toml> <out-dir>   generate symbols.gen.h (C) and symbols.gen.hpp (C++)
    anvil check <plugin-dir> [--exe eu4.exe]
                validate plugin.toml and symbols.toml; with --exe also compare
                every declaration with the game file, without starting the game

Symbol ids are the declaration order in symbols.toml; Anvil reads the same
shipped file, so the generated header and the check always agree.
"""
import re
import struct
import sys
import tomllib
from pathlib import Path

MEMORY = {"code", "read", "write"}


def load_symbols(path):
    data = tomllib.loads(Path(path).read_text(encoding="utf-8"))
    symbols = []
    for index, (name, s) in enumerate(data.get("symbol", {}).items()):
        if "signature" in s:
            kind = "function"
        elif "points_to" in s:
            kind = "slot"
        elif "type" in s:
            kind = "data"
        else:
            kind = "site"
        symbols.append({"id": index, "name": name, "kind": kind, **s})
    return data.get("build"), symbols


def parse_signature(sig):
    m = re.fullmatch(r"\s*(.+?)\s*\((.*)\)\s*", sig)
    if not m:
        raise SystemExit(f"bad signature: {sig!r}")
    return m.group(1), m.group(2).strip() or "void"


def gen(symbols_path, out_dir):
    build, symbols = load_symbols(symbols_path)
    out = Path(out_dir)
    out.mkdir(parents=True, exist_ok=True)
    head = f"/* generated by `anvil gen` from {Path(symbols_path).name} for {build}; do not edit */\n"
    c = [head, "#pragma once\n#include <anvil/anvil.h>\n", "enum {"]
    c += [f"    SYM_{s['name'].upper()} = {s['id']},  /* {s['kind']} at RVA 0x{s['rva']:X} */" for s in symbols]
    c.append("};")
    for s in symbols:
        if s["kind"] == "function":
            ret, params = parse_signature(s["signature"])
            c.append(f"typedef {ret} (*sym_{s['name']}_fn)({params});")
    cpp = [head, "#pragma once\n#include <anvil/anvil.hpp>\n", "namespace sym {"]
    for s in symbols:
        note = f"  // {s['note']}" if "note" in s else ""
        if s["kind"] == "function":
            ret, params = parse_signature(s["signature"])
            t = f"anvil::Function<{ret}({'' if params == 'void' else params})>"
        elif s["kind"] == "slot":
            t = "anvil::Slot"
        elif s["kind"] == "data":
            t = f"anvil::Data<{s['type']}>"
        else:
            t = "anvil::Site"
        cpp.append(f"inline constexpr {t} {s['name']}{{{s['id']}}};{note}")
    cpp.append("}  // namespace sym")
    (out / "symbols.gen.h").write_text("\n".join(c) + "\n", encoding="utf-8")
    (out / "symbols.gen.hpp").write_text("\n".join(cpp) + "\n", encoding="utf-8")


def pattern(text):
    tokens = text.split()
    if not tokens or not all(re.fullmatch(r"[0-9A-Fa-f]{2}|\?\?", t) for t in tokens):
        return None
    return [None if t == "??" else int(t, 16) for t in tokens]


class Image:
    """Just enough PE parsing to map an RVA to file bytes and section rights."""

    def __init__(self, path):
        self.raw = Path(path).read_bytes()
        pe = struct.unpack_from("<I", self.raw, 0x3C)[0]
        count = struct.unpack_from("<H", self.raw, pe + 6)[0]
        opt_size = struct.unpack_from("<H", self.raw, pe + 20)[0]
        self.image_base = struct.unpack_from("<Q", self.raw, pe + 24 + 24)[0]
        self.sections = []
        at = pe + 24 + opt_size
        for _ in range(count):
            name = self.raw[at:at + 8].rstrip(b"\0").decode(errors="replace")
            vsize, va, rsize, rptr = struct.unpack_from("<IIII", self.raw, at + 8)
            flags = struct.unpack_from("<I", self.raw, at + 36)[0]
            memory = "code" if flags & 0x20000000 else "write" if flags & 0x80000000 else "read"
            self.sections.append((name, va, max(vsize, rsize), rptr, rsize, memory))
            at += 40

    def section(self, rva):
        return next((s for s in self.sections if s[1] <= rva < s[1] + s[2]), None)

    def read(self, rva, size):
        s = self.section(rva)
        if s is None or rva - s[1] + size > s[4]:
            return None
        off = s[3] + rva - s[1]
        return self.raw[off:off + size]


def check(plugin_dir, exe=None):
    plugin_dir = Path(plugin_dir)
    problems = []
    manifest = tomllib.loads((plugin_dir / "plugin.toml").read_text(encoding="utf-8"))
    for key in ("id", "version", "api", "entry", "symbols"):
        if key not in manifest:
            problems.append(f"plugin.toml: missing `{key}`")
    build, symbols = load_symbols(plugin_dir / manifest.get("symbols", "symbols.toml"))
    if not build:
        problems.append("symbols.toml: missing `build`")
    image = Image(exe) if exe else None
    for s in symbols:
        where = f"symbols.toml: {s['name']}"
        if not isinstance(s.get("rva"), int):
            problems.append(f"{where}: `rva` must be an integer")
            continue
        if s.get("memory") not in MEMORY:
            problems.append(f"{where}: `memory` must be one of code, read, write")
        if s["kind"] == "slot":
            expected = None
        else:
            expected = pattern(s.get("bytes", ""))
            if expected is None or all(b is None for b in expected):
                problems.append(f"{where}: `bytes` must be hex pairs or ?? with at least one fixed byte")
                continue
        if image is None:
            continue
        sec = image.section(s["rva"])
        if sec is None:
            problems.append(f"{where}: RVA 0x{s['rva']:X} is outside {Path(exe).name}")
            continue
        if sec[5] != s.get("memory"):
            problems.append(f"{where}: declared {s.get('memory')} memory, {sec[0]} is {sec[5]}")
        if s["kind"] == "slot":
            raw = image.read(s["rva"], 8)
            value = struct.unpack("<Q", raw)[0] - image.image_base if raw else None
            if value != s["points_to"]:
                problems.append(f"{where}: points to {value and hex(value)}, expected 0x{s['points_to']:X}")
            continue
        actual = image.read(s["rva"], len(expected))
        for i, b in enumerate(expected):
            if b is not None and (actual is None or actual[i] != b):
                got = "nothing" if actual is None else f"{actual[i]:02X}"
                problems.append(f"{where}: byte {i} at RVA 0x{s['rva'] + i:X} is {got}, expected {b:02X}")
                break
    status = "checked against " + Path(exe).name if exe else "checked without a game file (pass --exe to compare bytes)"
    for p in problems:
        print("error:", p)
    print(f"{manifest.get('id', '?')}: {len(symbols)} symbol(s) for {build}, {status}: "
          f"{'OK' if not problems else str(len(problems)) + ' problem(s)'}")
    return 1 if problems else 0


if __name__ == "__main__":
    args = sys.argv[1:]
    if len(args) == 3 and args[0] == "gen":
        gen(args[1], args[2])
    elif len(args) in (2, 4) and args[0] == "check":
        sys.exit(check(args[1], args[3] if len(args) == 4 and args[2] == "--exe" else None))
    else:
        raise SystemExit(__doc__)
