/// A plugin: one value, created by [`plugin!`] when Anvil loads the DLL and
/// kept for the life of the process.
///
/// Request the changes in [`load`](Plugin::load); Anvil enables them together
/// when it returns `Ok`. Return an error (or let a host call's error propagate
/// with `?`) to refuse loading: Anvil rolls back everything the plugin staged.
pub trait Plugin: Sized + 'static {
    /// Called once, in the phase `plugin.toml` names.
    fn load(host: &mut Host) -> Result<Self>;
}

/// Exports `anvil_plugin_load` for the plugin type: `anvil::plugin!(MyPlugin);`
/// once, at the root of the plugin's `cdylib`.
#[macro_export]
macro_rules! plugin {
    ($plugin:ty) => {
        /// The entry point Anvil calls once (generated by `anvil::plugin!`).
        ///
        /// # Safety
        /// Called by Anvil with its host table and this plugin's handle.
        #[unsafe(no_mangle)]
        pub unsafe extern "C" fn anvil_plugin_load(
            host: *const $crate::sys::AnvilHost,
            plugin: *mut $crate::sys::AnvilPlugin,
        ) -> $crate::sys::AnvilResult {
            // SAFETY: forwarded from Anvil, which calls this export once.
            unsafe { $crate::__private::load::<$plugin>(host, plugin) }
        }

        const _: $crate::sys::AnvilPluginLoadFn = anvil_plugin_load;
    };
}

#[doc(hidden)]
pub mod __private {
    use crate::sys::{
        AnvilHost, AnvilPlugin, AnvilResult, ANVIL_API_VERSION, ANVIL_ERROR_INTERNAL,
        ANVIL_ERROR_INVALID_ARGUMENT, ANVIL_ERROR_UNSUPPORTED, ANVIL_OK,
    };
    use crate::{host, panic, Host, LogLevel, Plugin};

    /// What `plugin!` exports.
    ///
    /// # Safety
    /// `table` is Anvil's host table (or null) and `plugin` this plugin's
    /// handle, both valid for the life of the process.
    pub unsafe fn load<P: Plugin>(
        table: *const AnvilHost,
        plugin: *mut AnvilPlugin,
    ) -> AnvilResult {
        // SAFETY: see the contract above.
        let Some(table) = (unsafe { table.as_ref() }) else {
            return ANVIL_ERROR_INVALID_ARGUMENT;
        };
        if table.api_version != ANVIL_API_VERSION
            || !host::covers_api_2_0(table)
            || plugin.is_null()
        {
            return ANVIL_ERROR_UNSUPPORTED;
        }
        host::install(table, plugin);
        panic::install_hook();
        let mut host = Host::from_parts(table, plugin);
        match panic::catch(|| P::load(&mut host)) {
            Ok(Ok(loaded)) => {
                // Kept for the process, as Anvil keeps the DLL: its changes stay.
                std::mem::forget(loaded);
                ANVIL_OK
            }
            Ok(Err(error)) => {
                host.log(LogLevel::Error, format_args!("load() failed: {error}"));
                error.code().result()
            }
            Err(message) => {
                host.log(LogLevel::Error, format_args!("load() panicked: {message}"));
                ANVIL_ERROR_INTERNAL
            }
        }
    }
}
