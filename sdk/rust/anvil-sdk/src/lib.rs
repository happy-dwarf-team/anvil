//! Safe Rust API for plugins of [Anvil](https://github.com/happy-dwarf-team/anvil),
//! the native plugin loader for Europa Universalis IV 1.37.5.
//!
//! The crate sits on the raw bindings of [`anvil-sys`](sys) and adds what the C
//! ABI leaves to every plugin:
//!
//! - [`plugin!`]: exports `anvil_plugin_load`, creates the plugin with
//!   [`Plugin::load`] and turns an [`Error`] or a panic into the result Anvil
//!   rolls the plugin back on.
//! - Every callback Anvil or the game calls through an adapter of this crate
//!   (mid hooks, block replacements, events, settings, panel clicks, work for
//!   the main thread) runs under `catch_unwind`: a panic is logged once per
//!   callback and never crosses the FFI.
//! - [`Change`] is a handle whose `Drop` removes the change.
//! - Typed wrappers of the services Anvil ships: [`game`] (`anvil-game.game`),
//!   [`world`] (`anvil-game.world`), [`panel`] (`anvil-overlay.panel`),
//!   [`benchmark`] (`anvil.benchmark`), [`map`] (`anvil-map.modes`) and
//!   [`script`] (`anvil-script.day_end`).
//!
//! # Where `unsafe` stays
//!
//! Host and service calls are safe. What reaches the game's memory by address
//! or puts raw bytes and pointers into it stays an `unsafe fn` with its
//! contract: calling a hook's [`next`](FunctionHook::next) (the generated
//! function types are `unsafe extern "C" fn`), [`Host::function`],
//! [`Host::data`], writing the mid-hook context ([`Cpu::regs_mut`]), byte
//! patches, pointer swaps, call redirects, import replacements and changes at
//! raw addresses.
//!
//! # A plugin
//!
//! ```no_run
//! use anvil::{Change, Host, Plugin};
//!
//! #[allow(dead_code)]
//! mod sym {
//!     // anvil gen --lang rust symbols.toml writes this file (build.rs).
//!     pub const IDLE_EXIT: u32 = 0;
//! }
//!
//! struct Hello {
//!     // Dropping a Change removes it; the plugin is kept for the process.
//!     _idle_exit: Change,
//! }
//!
//! impl Plugin for Hello {
//!     fn load(host: &mut Host) -> anvil::Result<Self> {
//!         host.info(format_args!("hello from Rust on Anvil {}", host.anvil_version()));
//!         let log = *host;
//!         let idle_exit = host.mid_hook(sym::IDLE_EXIT, move |cpu| {
//!             log.info(format_args!("returning to the menu (rcx={:#x})", cpu.rcx));
//!         })?;
//!         Ok(Hello { _idle_exit: idle_exit })
//!     }
//! }
//!
//! anvil::plugin!(Hello);
//! ```
//!
//! Versions: this crate has its own `0.x` line; the source compatibility of
//! Anvil's ADR 0001 covers it from its 1.0.
#![deny(unsafe_op_in_unsafe_fn)]
